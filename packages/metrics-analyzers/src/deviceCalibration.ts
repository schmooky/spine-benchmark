/**
 * MEASURED per-device calibration: predicts frameCpuMs (CPU compute per frame)
 * for a spine on a specific real device we benchmarked, from its pose features.
 *
 * This REPLACES prediction through the hand-tuned poseImpact weights, which fit
 * the real fleet at R2 = 0.02 (i.e. not at all). Each device's model is an OLS
 * refit of its own measured frameCpuMs against scene-total pose features; the
 * honest error is the 5-fold held-out MAPE stored per device (~19-27% on the
 * clean 0.6.1 cohort). Keyed per DEVICE, not GPU family - same GPU can differ 2x
 * in CPU compute across SoCs.
 *
 * The data lives in ../data/device-calibration.json, regenerated by
 * tools/calibration/build-device-calibration.mjs. Consumers load that JSON
 * (import or fetch) and pass it to these pure helpers.
 *
 * Honest scope: CPU compute only. GPU fill has no in-browser timer, so it is not
 * in this model; the runner's wall-clock frame time carries GPU whenever a scene
 * drops below refresh.
 */

/** One benchmarked device's fitted linear model. */
export interface DeviceCalModel {
  deviceLabel: string;
  gpuFamily: unknown;
  clientVersion: string;
  runIds: string[];
  scenes: number;
  /** Linear weights aligned to `features`; ms = sum(weights[i] * feature[i]). */
  weights: number[];
  inSampleR2: number;
  /** 5-fold held-out MAPE - the number to show as the +/- error band. Null if
   * too few scenes to validate. */
  heldOutMape: number | null;
  /** True only when post-clamp (>= minTrustedClientVersion) AND held-out MAPE
   * is within the ceiling. Untrusted devices must not be shown as authoritative. */
  trusted: boolean;
}

export interface DeviceCalibration {
  schema: number;
  generatedAt: string;
  target: "frameCpuMs";
  unit: "ms";
  scope: string;
  minTrustedClientVersion: string;
  maxTrustedHeldOutMape: number;
  /** Feature order: matches the output of {@link sceneTotalFeatures}. */
  features: string[];
  featureNote: string;
  method: string;
  devices: DeviceCalModel[];
}

/**
 * Per-spine pose-feature inputs the calibration consumes. These come straight
 * off the canonical pose walker (a subset of ImpactFeatures / the runner's
 * `one`). All are per SINGLE spine; multiply by instances via `instances`.
 */
export interface CalFeatureInputs {
  vertices: number;
  deformedMeshes: number;
  weightedMeshes: number;
  coveredKpx: number;
  drawCallEst: number;
}

/**
 * Build the scene-total feature vector in the exact order the models expect:
 * [1, vertices, deformedMeshes, weightedMeshes, coveredKpx, drawCallEst] * inst.
 * A single dropped spine in the workbench uses instances = 1.
 */
export function sceneTotalFeatures(f: CalFeatureInputs, instances = 1): number[] {
  const I = instances || 1;
  return [
    1,
    f.vertices * I,
    f.deformedMeshes * I,
    f.weightedMeshes * I,
    f.coveredKpx * I,
    f.drawCallEst * I,
  ];
}

/** Look up a device's model by exact label (as reported by the runner). */
export function deviceModel(
  cal: DeviceCalibration,
  deviceLabel: string,
): DeviceCalModel | undefined {
  return cal.devices.find((d) => d.deviceLabel === deviceLabel);
}

/** Devices we can stand behind; pass trustedOnly=false to include the rest. */
export function calibratedDevices(
  cal: DeviceCalibration,
  opts: { trustedOnly?: boolean } = {},
): DeviceCalModel[] {
  const list = opts.trustedOnly === false ? cal.devices : cal.devices.filter((d) => d.trusted);
  return [...list].sort((a, b) => (a.heldOutMape ?? 1) - (b.heldOutMape ?? 1));
}

/**
 * Predicted frameCpuMs on this device for the given per-spine features.
 * Clamped at 0 (the OLS intercept + collinear features can dip a trivial spine
 * slightly negative; never report negative cost).
 */
export function predictDeviceMs(
  model: DeviceCalModel,
  f: CalFeatureInputs,
  instances = 1,
): number {
  const x = sceneTotalFeatures(f, instances);
  let ms = 0;
  for (let i = 0; i < model.weights.length; i++) ms += model.weights[i] * (x[i] ?? 0);
  return Math.max(0, ms);
}
